/** Deterministic asset preparation only; no lettering is generated here. */
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

// Reuse Wrangler's installed image codec for build tooling; no runtime dependency.
const require = createRequire(import.meta.url);
const sharp = createRequire(require.resolve("wrangler/package.json"))("sharp");
const source = readFileSync(new URL("../DOCS/White Cooper-Style Anyaparallax Wordmark.png", import.meta.url));
const sourceHash = createHash("sha256").update(source).digest("hex");
if (sourceHash !== "0000494a1d9d15155fc7cab42c3913c9dbcf6cbfb9295480698eabec77e5d5df") {
  throw new Error("Approved watermark source differs; review artwork before regenerating.");
}
// Preserve the full 3:1 canvas, texture, colour and alpha. No trim or recolouring.
const png = await sharp(source).resize({ width: 267 }).png({ compressionLevel: 9 }).toBuffer();
const hash = createHash("sha256").update(png).digest("hex");
const module = `/**
 * Operator-approved lowercase anyaparallax raster artwork.
 * Generated by scripts/prepare-watermark.mjs from the supplied PNG, not a font.
 * PNG SHA-256: ${hash}
 * Embedded at compile time so Workers need no filesystem or asset fetch.
 */
import type { WatermarkOverlay } from "./image-processor";

const PNG_BASE64 = "${png.toString("base64")}";

export function finalWatermarkOverlay(): WatermarkOverlay {
  return {
    bytes: Uint8Array.from(atob(PNG_BASE64), (character) => character.charCodeAt(0)),
    contentType: "image/png",
    label: "final anyaparallax watermark",
  };
}
`;
for (const [path, content] of [["../app/images/anyaparallax-watermark.png", png], ["../app/images/watermark-asset.ts", module]]) {
  const url = new URL(path, import.meta.url);
  if (process.argv.includes("--check")) {
    const actual = readFileSync(url);
    const matches = typeof content === "string"
      ? actual.toString("utf8").replaceAll("\r\n", "\n") === content
      : actual.equals(content);
    if (!matches) throw new Error(`Stale watermark asset: ${path}`);
  } else writeFileSync(url, content);
}
console.log(`Approved watermark: 267x89 PNG, ${png.length} bytes, SHA-256 ${hash}`);
